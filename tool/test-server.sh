#!/usr/bin/env bash
# Run an isolated portal media server for testing the app.
#
# Everything lives under $PORTAL_TEST_HOME (default ~/.portal-test): the
# server's config/index/thumbnails in .portal/, and generated test videos in
# media/. Your real ~/.portal is never touched; the test server also uses
# different ports (7843 media API, 5568 web UI) so it can run beside it.
#
#   tool/test-server.sh setup   # generate test videos + write config (idempotent)
#   tool/test-server.sh start   # run the server in the foreground (Ctrl-C to stop)
#   tool/test-server.sh token   # print the API token to enter in the app
#
# From the Android emulator connect to host 10.0.2.2, port 7843.
set -euo pipefail

PORTAL_TEST_HOME="${PORTAL_TEST_HOME:-$HOME/.portal-test}"
PORTAL_REPO="${PORTAL_REPO:-$HOME/projects/portal}"
MEDIA_PORT="${PORTAL_TEST_MEDIA_PORT:-7843}"
UI_PORT="${PORTAL_TEST_UI_PORT:-5568}"

DATA_DIR="$PORTAL_TEST_HOME/.portal"
MEDIA_DIR="$PORTAL_TEST_HOME/media"
CONFIG="$DATA_DIR/config.toml"

# name seconds width height fps audio(yes/no)
VIDEOS=(
  "01-short-30s          30 640 360 24 yes"
  "02-medium-10min      600 640 360 24 yes"
  "03-long-90min       5400 640 360 15 yes"
  "04-portrait-2min     120 360 640 24 yes"
  "05-silent-1min        60 640 360 24 no"
)

gen_video() {
  local name=$1 secs=$2 w=$3 h=$4 fps=$5 audio=$6
  local out="$MEDIA_DIR/$name.mp4"
  [[ -s "$out" ]] && { echo "exists  $out"; return; }
  echo "making  $out (${secs}s)"
  # Burn the timestamp into every frame so a seek can be verified from a
  # screenshot, plus a moving test pattern so playback is visibly moving.
  local vf="drawtext=text='$name':fontsize=28:fontcolor=white:box=1:boxcolor=black@0.6:boxborderw=8:x=(w-tw)/2:y=24,"
  vf+="drawtext=text='%{pts\\:hms}':fontsize=56:fontcolor=white:box=1:boxcolor=black@0.6:boxborderw=12:x=(w-tw)/2:y=(h-th)/2"
  local args=(-hide_banner -loglevel error -y
    -f lavfi -i "testsrc2=size=${w}x${h}:rate=${fps}")
  if [[ $audio == yes ]]; then
    args+=(-f lavfi -i "sine=frequency=440:beep_factor=4:sample_rate=44100")
  fi
  args+=(-t "$secs" -vf "$vf" -c:v libx264 -preset ultrafast -crf 28 -pix_fmt yuv420p)
  [[ $audio == yes ]] && args+=(-c:a aac -b:a 64k)
  args+=(-movflags +faststart "$out.part.mp4")
  ffmpeg "${args[@]}"
  mv "$out.part.mp4" "$out"
}

setup() {
  mkdir -p "$DATA_DIR" "$MEDIA_DIR/Test Videos"
  for spec in "${VIDEOS[@]}"; do
    # shellcheck disable=SC2086
    gen_video $spec
  done
  # A nested folder so browsing into a subfolder is exercised too.
  [[ -e "$MEDIA_DIR/Test Videos/06-nested-45s.mp4" ]] || \
    (MEDIA_DIR="$MEDIA_DIR/Test Videos" gen_video 06-nested-45s 45 640 360 24 yes)
  if [[ ! -s "$CONFIG" ]]; then
    cat > "$CONFIG" <<TOML
[agent]
media_api_bind = "0.0.0.0"
media_api_port = $MEDIA_PORT
web_ui_bind = "127.0.0.1"
web_ui_port = $UI_PORT
# api_token is generated by the server on first start.

[libraries]
allowlist = ["$MEDIA_DIR"]

[indexing]
mode = "background"
scan_on_startup = true

[thumbnails]
cache_dir = "$DATA_DIR/thumbnails"
max_cache_size_mb = 100
prefer_embedded = true

[logging]
log_dir = "$DATA_DIR/logs"
max_size_mb = 20
rotation = "size"
TOML
    chmod 600 "$CONFIG"
    echo "wrote   $CONFIG"
  fi
}

start() {
  setup
  [[ -x "$PORTAL_REPO/.venv/bin/python" ]] || {
    echo "no venv at $PORTAL_REPO/.venv; run 'uv sync' in $PORTAL_REPO" >&2; exit 1; }
  echo "starting test server: media API :$MEDIA_PORT, web UI http://127.0.0.1:$UI_PORT (HOME=$PORTAL_TEST_HOME)"
  # The server only reads \$HOME/.portal, so point HOME at the test home.
  cd "$PORTAL_TEST_HOME"
  exec env HOME="$PORTAL_TEST_HOME" "$PORTAL_REPO/.venv/bin/python" -m portal
}

token() {
  grep -E '^api_token' "$CONFIG" 2>/dev/null | sed -E 's/^api_token *= *"(.*)"/\1/' \
    || { echo "no token yet: start the server once" >&2; exit 1; }
}

case "${1:-}" in
  setup) setup ;;
  start) start ;;
  token) token ;;
  *) sed -n '2,13p' "$0"; exit 1 ;;
esac
